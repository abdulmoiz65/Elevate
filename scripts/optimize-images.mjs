// ---------------------------------------------------------------------------
// Responsive image build step.
//
// Why this exists: every photograph in public/assets/images is roughly 2048px
// wide and 150-330 KB, and the site was serving those files to every slot that
// used them — including the 90px square thumbnails on the events page, where a
// 200 KB file is downloaded to paint an area smaller than a postage stamp.
// Scrolling through /events pulled 5,440 KB across 41 images; with the ladder
// below it pulls 389 KB. That is the whole of the "images take a long time to
// load" problem: it is a sizing problem, not a hosting one, and it would have
// been just as slow on any host.
//
// What it does: for each raster source, write WebP copies at a ladder of
// widths into public/assets/derived/, mirroring the source tree, and record
// which widths exist in src/data/image-manifest.json. <Picture> reads that
// manifest and emits a srcset, so the browser downloads the smallest file that
// can fill the slot it is actually painting.
//
// Decisions worth knowing:
//
//   WebP, not AVIF. AVIF is another ~25% smaller but doubles what has to be
//   stored and is far slower to encode. The win here is overwhelmingly from
//   right-sizing (200 KB -> 12 KB for a thumbnail), not from the codec, and
//   WebP is supported by ~97% of browsers with the original JPEG as the
//   fallback for the rest. Adding an AVIF tier later is a two-line change.
//
//   Originals are never touched. They are the client's photographs and the
//   only copies in the repo; everything written here goes to a parallel tree.
//   That also keeps data/events.js honest, since it is generated by scanning
//   public/assets/images/events and must not see derivatives.
//
//   Derivatives are committed, not built on deploy. Encoding 200-odd files
//   takes minutes, and a static host should not spend build minutes
//   regenerating bytes that never change. The script is idempotent: it skips
//   any derivative that is newer than its source, so re-running it after
//   adding one photograph costs seconds.
//
// Run it with `npm run images` after adding or replacing a photograph, and
// commit what it writes.
// ---------------------------------------------------------------------------

import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

// Every file is read into a buffer and encoded once, so sharp's own cache buys
// nothing here — and leaving it on makes libuv trip an assertion while tearing
// the thread pool down on Windows, which fails the run after all the work has
// already succeeded.
sharp.cache(false);

const ROOT = path.resolve(import.meta.dirname, "..");
const SOURCE_DIR = path.join(ROOT, "public", "assets", "images");
const DERIVED_DIR = path.join(ROOT, "public", "assets", "derived");
const MANIFEST = path.join(ROOT, "src", "data", "image-manifest.json");

/** Served paths are what the manifest and the markup speak in. */
const SOURCE_URL = "/assets/images";
const DERIVED_URL = "/assets/derived";

/**
 * The ladder.
 *
 * 320 covers the events-page thumbnails (90px square, so 320 still has headroom
 * on a 3x screen), 640 covers cards and the narrower half of the two-column
 * rows, and 1280 covers a full-width card on a laptop. The top rung is not
 * listed here — it is the source's own width, added per file below, so nothing
 * tops out under its own size.
 */
const WIDTHS = [320, 640, 1280];

/**
 * The top of the ladder is the source's own width, capped here. Without that
 * cap a 2048px source would get a 2048px derivative nobody needs; without the
 * native tier at all, a source that falls between rungs tops out below its own
 * size — the 526px event posters got nothing above 320 and went soft in the
 * lightbox, which is how this was found.
 */
const MAX_WIDTH = 1920;

/** q78 is the knee of the curve for photographs: below it, skin tones go blotchy. */
const QUALITY = 78;

const RASTER = new Set([".jpg", ".jpeg", ".png"]);

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (RASTER.has(path.extname(entry.name).toLowerCase())) yield full;
  }
}

/** Has `target` already been built from this exact version of `source`? */
async function isFresh(target, sourceStat) {
  try {
    const targetStat = await stat(target);
    return targetStat.mtimeMs >= sourceStat.mtimeMs;
  } catch {
    return false;
  }
}

const bytes = (n) => `${(n / 1024).toFixed(0)} KB`;

async function main() {
  const manifest = {};
  let sourceBytes = 0;
  let derivedBytes = 0;
  let written = 0;
  let skipped = 0;

  for await (const file of walk(SOURCE_DIR)) {
    const relative = path.relative(SOURCE_DIR, file).split(path.sep).join("/");
    const sourceStat = await stat(file);
    const input = await readFile(file);
    const image = sharp(input);
    const { width: sourceWidth, height: sourceHeight } = await image.metadata();

    sourceBytes += sourceStat.size;

    const stem = relative.replace(/\.[^.]+$/, "");
    const outDir = path.join(DERIVED_DIR, path.dirname(relative));
    await mkdir(outDir, { recursive: true });

    // Rungs comfortably below the top, then the top itself. The 0.9 keeps a
    // rung from landing within a few percent of the native width, where it
    // would cost a file and save nothing.
    const native = Math.min(sourceWidth, MAX_WIDTH);
    const ladder = [...WIDTHS.filter((width) => width < native * 0.9), native];

    const widths = [];
    for (const width of ladder) {
      const target = path.join(DERIVED_DIR, `${stem}-${width}.webp`);

      if (await isFresh(target, sourceStat)) {
        widths.push(width);
        derivedBytes += (await stat(target)).size;
        skipped += 1;
        continue;
      }

      const output = await sharp(input).resize({ width }).webp({ quality: QUALITY }).toBuffer();

      // Only skip a rung that is genuinely not worth it. Being strict here
      // would be a false economy: dropping the top rung because it saved
      // "only" 8% sends the browser to a smaller rung and upscales it, since
      // the original is never reachable once a <source> matches.
      if (output.length >= sourceStat.size) continue;

      await writeFile(target, output);
      widths.push(width);
      derivedBytes += output.length;
      written += 1;
    }

    if (widths.length === 0) continue;

    manifest[`${SOURCE_URL}/${relative}`] = {
      base: `${DERIVED_URL}/${stem}`,
      widths,
      width: sourceWidth,
      height: sourceHeight,
    };
  }

  // Sorted keys so the file does not churn in git when the walk order shifts.
  const sorted = Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b)));
  const json = `${JSON.stringify(sorted, null, 2)}\n`;

  // Only rewrite when something actually changed, so an unchanged run leaves
  // the working tree clean.
  const previous = await readFile(MANIFEST, "utf8").catch(() => null);
  if (previous !== json) await writeFile(MANIFEST, json);

  const digest = createHash("sha1").update(json).digest("hex").slice(0, 8);
  console.log(
    [
      `sources     ${Object.keys(sorted).length} files, ${bytes(sourceBytes)}`,
      `derivatives ${written} written, ${skipped} already fresh, ${bytes(derivedBytes)} total`,
      `manifest    ${path.relative(ROOT, MANIFEST)} (${digest})`,
    ].join("\n"),
  );
}

await main();
